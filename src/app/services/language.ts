@Injectable({
  providedIn: 'root',
})
export class LanguageService {
  private readonly storageKey = 'ez_trucks_language';
  readonly language = signal<LanguageCode>(this.readLanguage());

  setLanguage(language: LanguageCode): void {
    localStorage.setItem(this.storageKey, language);
    this.language.set(language);
    document.documentElement.lang = language;
  }

  t(key: string): string {
    return translations[this.language()][key] ?? translations.nl[key] ?? key;
  }

  private readLanguage(): LanguageCode {
    const stored = localStorage.getItem(this.storageKey);

    if (stored === 'fr' || stored === 'en' || stored === 'nl') {
      document.documentElement.lang = stored;
      return stored;
    }

    return 'nl';
  }
}
